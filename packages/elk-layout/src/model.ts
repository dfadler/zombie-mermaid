/**
 * Flowchart model for the ELK layout: parses with this repo's parser, then sizes nodes and
 * edge labels the way mermaid sees them with the default flowchart config (look neo,
 * padding 15, wrappingWidth 120, minNodeWidth 120, 16px font).
 *
 * Shapes and features this module cannot size faithfully throw UnsupportedFlowchartError so
 * the caller can fall back to its own layout.
 */
import { measureTextWidth } from '@zombie-mermaid/core'
import { parseMermaid } from '@zombie-mermaid/mermaid-parser'
import advances from './font-advances.json' with { type: 'json' }

export type Kind =
  | 'rect'
  | 'round'
  | 'diamond'
  | 'stadium'
  | 'circle'
  | 'double'
  | 'hex'
  | 'subr'
  | 'cyl'
export interface MNode {
  id: string
  label: string
  kind: Kind
  w: number
  h: number
}
export interface MEdge {
  id: string
  from: string
  to: string
  label?: string
  lw: number
  lh: number
  arrowEnd: boolean
  arrowStart: boolean
}
export interface Model {
  dir: 'TB' | 'BT' | 'LR' | 'RL'
  nodes: MNode[]
  edges: MEdge[]
}
export interface Pt {
  x: number
  y: number
}

/** Thrown for input the layout cannot reproduce; callers should fall back. */
export class UnsupportedFlowchartError extends Error {
  constructor(readonly reasons: string[]) {
    super(`unsupported flowchart for ELK layout: ${reasons.join('; ')}`)
    this.name = 'UnsupportedFlowchartError'
  }
}

const WRAP = 120 // flowchart.wrappingWidth / minNodeWidth
const LINE_H = 24

// Per-char advances of mermaid's label font ("trebuchet ms", 16px) as the oracle's Chromium
// measures them (see README: regenerated by `pnpm run elk-layout:font`). Characters outside
// printable ASCII fall back to the repo's Inter metrics scaled to the same font.
const ADV = advances as Record<string, number>
const textW = (t: string) =>
  [...t].reduce(
    (w, c) => w + (ADV[c] ?? measureTextWidth(c, 16, 400) * 0.93),
    0,
  )

/** Greedy word wrap at `max` px; returns the widest line and the line count. */
function wrap(label: string, max: number): { w: number; lines: number } {
  let lines = 0
  let widest = 0
  for (const para of label.split(/<br\s*\/?>|\n/i)) {
    let cur = ''
    let n = 0
    for (const word of para.split(/\s+/).filter(Boolean)) {
      const next = cur ? `${cur} ${word}` : word
      if (cur && textW(next) > max) {
        widest = Math.max(widest, textW(cur))
        n++
        cur = word
      } else cur = next
    }
    widest = Math.max(widest, textW(cur))
    lines += n + 1
  }
  return { w: widest, lines: Math.max(1, lines) }
}

const KINDS: Record<string, Kind> = {
  rectangle: 'rect',
  rounded: 'round',
  diamond: 'diamond',
  stadium: 'stadium',
  circle: 'circle',
  doublecircle: 'double',
  hexagon: 'hex',
  subroutine: 'subr',
  cylinder: 'cyl',
}

export function buildModel(src: string): Model {
  const g = parseMermaid(src)
  const reasons: string[] = []
  if (g.subgraphs.length) reasons.push('subgraphs')
  for (const n of g.nodes.values())
    if (!KINDS[n.shape]) reasons.push(`shape "${n.shape}" (node ${n.id})`)
  if (reasons.length) throw new UnsupportedFlowchartError(reasons)

  const dir = (g.direction === 'TD' ? 'TB' : g.direction) as Model['dir']
  const nodes: MNode[] = [...g.nodes.values()].map((n) => {
    const { w, lines } = wrap(n.label, WRAP)
    const tw = Math.max(w, WRAP)
    const th = lines * LINE_H
    const kind = KINDS[n.shape]!
    const base = { id: n.id, label: n.label, kind }
    // Constants fitted against the oracle (rect 120x24 text -> 152x48, round 150x54, diamond 174x174).
    switch (kind) {
      case 'round':
        return { ...base, w: tw + 30, h: th + 30 }
      // Wrapped (multi-line) stadium/hexagon labels come out ~6.3px / ~13.7px wider than the
      // wrap width in the oracle; the constants below are empirical.
      case 'stadium':
        return { ...base, w: (lines > 1 ? 126.3 : tw) + 52, h: th + 24 }
      case 'circle':
      case 'double': {
        const d = Math.hypot(tw, th) + (kind === 'double' ? 56 : 64)
        return { ...base, w: d, h: d }
      }
      case 'hex':
        return { ...base, w: lines > 1 ? 219.4 : 205.7, h: th + 70 }
      case 'subr':
        return { ...base, w: tw + 44, h: th + 12 }
      case 'cyl':
        return { ...base, w: tw + 24, h: th + 64.1 }
      case 'diamond':
        return { ...base, w: tw + th + 30, h: tw + th + 30 }
      default:
        return { ...base, w: tw + 32, h: th + 24 }
    }
  })
  const seen = new Map<string, number>()
  const edges: MEdge[] = g.edges.map((e) => {
    const k = `${e.source}\0${e.target}`
    const c = seen.get(k) ?? 0
    seen.set(k, c + 1)
    // mermaid's flowDb ids: L_<a>_<b>_<0,2,3,4...> (the 2nd edge between a pair skips 1)
    const id = `L_${e.source}_${e.target}_${c === 0 ? 0 : c + 1}`
    return {
      id: e.id ?? id,
      from: e.source,
      to: e.target,
      label: e.label,
      lw: e.label ? wrap(e.label, 200).w : 0,
      lh: e.label ? LINE_H : 0,
      arrowEnd: e.hasArrowEnd,
      arrowStart: e.hasArrowStart,
    }
  })
  return { dir, nodes, edges }
}

/** Does the point (relative to node centre) lie inside the node outline? */
export const inside = (n: MNode, dx: number, dy: number): boolean =>
  n.kind === 'diamond'
    ? Math.abs(dx) / (n.w / 2) + Math.abs(dy) / (n.h / 2) <= 1
    : Math.abs(dx) <= n.w / 2 && Math.abs(dy) <= n.h / 2
