/** Total kerning of `text` in em (negative: the text is narrower). */
export function trebuchetKerning(text: string): number {
  let units = 0
  const cs = [...text]
  for (let i = 1; i < cs.length; i++)
    units += PAIRS.get(cs[i - 1]! + cs[i]!) ?? 0
  return units / UNITS_PER_EM
}
