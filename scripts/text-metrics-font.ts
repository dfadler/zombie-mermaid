/**
 * Regenerates packages/core/src/trebuchet-advances.ts: per-character advances (printable ASCII,
 * regular and bold) of mermaid 12.3.0's label font `"trebuchet ms", verdana, arial, sans-serif`
 * at 16px, as this machine's headless Chromium resolves it. Machine-specific (installed fonts
 * decide what the stack falls back to); the committed table is the macOS Trebuchet MS one,
 * the same font `scripts/elk-layout-font.ts` measures. Needs Chromium.
 */
import { writeFileSync } from 'node:fs'
import { startRealMermaid } from './lib/real-mermaid.ts'

const s = await startRealMermaid()
const adv = await s.page.evaluate(() => {
  const c = document.createElement('canvas').getContext('2d')!
  const out: Record<number, number[]> = {}
  for (const w of [400, 700]) {
    c.font = `${w} 16px "trebuchet ms", verdana, arial, sans-serif`
    out[w] = []
    for (let i = 32; i < 127; i++)
      out[w].push(c.measureText(String.fromCharCode(i)).width)
  }
  return out
})
await s.close()
const arr = (a: number[]) => `[${a.join(', ')}]`
writeFileSync(
  new URL('../packages/core/src/trebuchet-advances.ts', import.meta.url),
  `// Generated by scripts/text-metrics-font.ts; do not edit. Advances in px at 16px, U+0020..U+007E.
export const TREBUCHET_REGULAR: readonly number[] = ${arr(adv[400]!)}
export const TREBUCHET_BOLD: readonly number[] = ${arr(adv[700]!)}
`,
)
console.log('wrote', adv[400]!.length, 'advances x 2 weights')
